// Render Products Grid
function renderProducts() {
  const container = document.getElementById("dealsContainer");
  if (!container) return;

  const filtered = catalog.filter(item => {
    const cat = classifyProduct(item);
    let matchesCategory = false;
    if (currentCategory === "all") {
      matchesCategory = true;
    } else if (currentCategory === "under499") {
      matchesCategory = Number(item.dealPrice || item.price || 0) <= 499 && Number(item.dealPrice || item.price || 0) > 0;
    } else if (currentCategory === "lowestprice") {
      matchesCategory = (parseInt(item.discount || "0") >= 60) || (item.badge && item.badge.includes("UNDER"));
    } else if (currentCategory === "mobiles") {
      matchesCategory = cat === "mobiles";
    } else if (currentCategory === "electronics") {
      matchesCategory = cat === "electronics";
    } else if (currentCategory === "footwear") {
      matchesCategory = cat === "footwear";
    } else if (currentCategory === "women") {
      matchesCategory = cat === "women";
    } else if (currentCategory === "men") {
      matchesCategory = cat === "men";
    } else if (currentCategory === "girls") {
      matchesCategory = item.department === "girls" || item.category === "girls" || /\b(girl|girls|frock|frocks|kids|kid|dungaree)\b/i.test(item.title);
    } else if (currentCategory === "fashion") {
      matchesCategory = cat === "fashion" || cat === "women" || cat === "men";
    } else if (currentCategory === "home") {
      matchesCategory = cat === "home";
    } else if (currentCategory === "finance") {
      matchesCategory = item.category === "finance";
    } else {
      matchesCategory = cat === currentCategory;
    }

    const matchesSearch = !searchQuery ||
      item.title.toLowerCase().includes(searchQuery.toLowerCase()) ||
      (item.brand && item.brand.toLowerCase().includes(searchQuery.toLowerCase())) ||
      (item.store && item.store.toLowerCase().includes(searchQuery.toLowerCase())) ||
      (item.discount && item.discount.toLowerCase().includes(searchQuery.toLowerCase()));
    return matchesCategory && matchesSearch;
  });

  if (filtered.length === 0) {
    container.innerHTML = `
      <div class="empty-state">
        <div style="font-size: 40px; margin-bottom: 12px;">🔍</div>
        <h3>No matching products found</h3>
        <p>Try searching for a different keyword or switch category tabs above.</p>
      </div>
    `;
    return;
  }

  container.innerHTML = filtered.map(item => createProductCardHtml(item)).join("");
}

function handleCardImgError(imgEl, fallbackUrl) {
  if (fallbackUrl && imgEl.src !== fallbackUrl) {
    imgEl.src = fallbackUrl;
    return;
  }
  imgEl.onerror = null;
  imgEl.src = 'data:image/svg+xml;utf8,<svg xmlns="http://www.w3.org/2000/svg" width="160" height="160" viewBox="0 0 160 160"><rect width="100%" height="100%" fill="%23f8fafc"/><circle cx="80" cy="80" r="32" fill="%23f1f5f9"/><text x="50%" y="54%" dominant-baseline="middle" text-anchor="middle" font-size="28">🛍️</text><text x="50%" y="78%" dominant-baseline="middle" text-anchor="middle" fill="%2394a3b8" font-size="11" font-weight="700" font-family="-apple-system,BlinkMacSystemFont,Segoe UI,Roboto,sans-serif">TheBhom</text></svg>';
}

// Create Flipkart/Amazon Style Compact Product Card
function createProductCardHtml(item) {
  const dealPrice = Number(item.dealPrice ?? item.price ?? 0);
  const origPrice = Number(item.originalPrice ?? item.mrp ?? 0);
  const isFree = dealPrice === 0;
  const formattedPrice = isFree ? "FREE" : `₹${dealPrice.toLocaleString("en-IN")}`;
  const formattedOriginalPrice = origPrice > dealPrice ? `₹${origPrice.toLocaleString("en-IN")}` : "";
  
  // Robust detailUrl (prevents 404 on missing slug)
  let detailUrl = "/deals/";
  if (item.dedicatedPage) {
    try {
      const u = new URL(item.dedicatedPage, window.location.origin);
      detailUrl = u.pathname;
    } catch (e) {
      detailUrl = item.dedicatedPage;
    }
  } else if (item.slug) {
    detailUrl = `/deals/p/${item.slug.replace(/\.html$/, "")}.html`;
  } else if (item.id || item.pid || item.asin) {
    const code = (item.id || item.pid || item.asin).toLowerCase();
    detailUrl = `/deals/p/${code}.html`;
  }

  const isLowestPrice = (parseInt(item.discount || "0") >= 60) || (dealPrice <= 499 && dealPrice > 0);
  const cleanDiscount = (item.discount && item.discount.length <= 15) ? escapeHtml(item.discount) : "DEAL";
  const buyUrl = item.profitLink || item.url || (item.asin ? `https://www.amazon.in/dp/${item.asin}?tag=bhom120704-21` : detailUrl);
  const primaryImg = item.cleanImage || item.image || "";
  const fallbackImg = (item.image && item.cleanImage && item.image !== item.cleanImage) ? item.image : "";

  return `
    <article class="product-card" data-id="${item.id}">
      
      <!-- Top Image Container -->
      <div class="product-thumb-box" style="position:relative;">
        <a href="${detailUrl}" class="thumb-link" title="${escapeHtml(item.title)}">
          <img class="product-img" src="${primaryImg}" alt="${escapeHtml(item.title)}" loading="lazy" referrerpolicy="no-referrer" style="max-height:160px; max-width:160px; object-fit:contain;" onerror="handleCardImgError(this, '${escapeHtml(fallbackImg)}')">
        </a>
        <span class="discount-badge">${cleanDiscount}</span>
        <span class="store-badge ${String(item.store).toLowerCase().replace(/\s+/g, '-')}">${escapeHtml(item.store)}</span>
        ${isLowestPrice ? `<span class="lowest-price-tag" style="position:absolute; bottom:6px; left:6px; background:#ecfdf5; color:#047857; font-size:10px; font-weight:800; padding:2px 6px; border-radius:4px; border:1px solid #a7f3d0; letter-spacing:0.2px;">📉 Lowest Price Ever</span>` : ""}
      </div>

      <!-- Card Details Body -->
      <div class="product-info-box">
        
        <!-- Brand & Title -->
        <span class="product-brand">${escapeHtml(item.brand || item.store)}</span>
        <h3 class="product-name">
          <a href="${detailUrl}" title="${escapeHtml(item.title)}">${escapeHtml(item.title)}</a>
        </h3>

        <!-- Rating -->
        <div class="rating-strip">
          <span class="star-pill">★ ${item.rating || "4.3"}</span>
          <span class="rating-count">(${Number(item.reviewsCount || 1200).toLocaleString("en-IN")})</span>
        </div>

        <!-- Pricing Row -->
        <div class="price-strip">
          <span class="price-current">${formattedPrice}</span>
          ${formattedOriginalPrice ? `<span class="price-mrp">${formattedOriginalPrice}</span>` : ""}
        </div>

        <!-- Two Primary Action Buttons: BUY NOW + SEE DETAILS -->
        <div class="product-btn-group">
          <a href="${buyUrl}" target="_blank" rel="noopener noreferrer nofollow" class="btn-buy-now">
            <span>Buy Now</span>
            <svg width="13" height="13" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5"><path d="M5 12h14M12 5l7 7-7 7"/></svg>
          </a>
          <a href="${detailUrl}" class="btn-see-details">
            <span>See Details</span>
          </a>
        </div>

      </div>

    </article>
  `;
}

// Event Listeners
function setupEventListeners() {
  // Category tabs
  const tabs = document.querySelectorAll(".cat-tab");
  tabs.forEach(tab => {
    tab.addEventListener("click", () => {
      tabs.forEach(t => t.classList.remove("active"));
      tab.classList.add("active");
      currentCategory = tab.dataset.category;
      renderProducts();
    });
  });

  // Search input
  const searchInput = document.getElementById("searchInput");
  const clearBtn = document.getElementById("clearSearchBtn");

  if (searchInput) {
    searchInput.addEventListener("input", (e) => {
      searchQuery = e.target.value.trim();
      if (clearBtn) clearBtn.style.display = searchQuery ? "block" : "none";
      renderProducts();
    });
  }

  if (clearBtn && searchInput) {
    clearBtn.addEventListener("click", () => {
      searchInput.value = "";
      searchQuery = "";
      clearBtn.style.display = "none";
      renderProducts();
      searchInput.focus();
    });
  }
}

// Toast helper
function showToast(message) {
  const toast = document.getElementById("toast");
  if (!toast) return;
  toast.textContent = message;
  toast.classList.add("visible");
  setTimeout(() => toast.classList.remove("visible"), 2500);
}

// Escape HTML
function escapeHtml(text) {
  if (!text) return "";
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}
